"""G79: reuse frozen PAR2 selection with G78's human-educated relevance tables.

Git objects are verified reference code in this external experiment, not code
generated by a learner. Production leobot/ never imports this module.
"""
import ast
import gc
import hashlib
import json
import math
import os
from pathlib import Path
import random
import resource
import subprocess
import sys
import time
import types

from leobot import Bot
from experiments import g60_calibrar_confianza as g60
from experiments.g57_kiosco import businesses, contains, plain
from experiments.g68_confianza import TRAIN, DEV, collect, isotonic
from experiments.g74_relation_coverage import ROOT, ENGINE, BASE_SHA
from experiments.g75_relational_evidence import public_measure

REFERENCE = 'fe2f3116e8d2bf0a6c76eabfce496dbb4780d973'
REFERENCE_HASHES = {
    'leobot/context.py': '3c907f07775aa9da574df693fa043a33ae773adc8ff78ec6470d6a86f93feddd',
    'experiments/par2_seleccion.py': '54d4337cdd9d5bfeaa482cb9ba89de248d2d4fbe45c567e29c62bac9c0397eb1',
}
G78_SHA = '630399f00c5aa06e987a564b46544f88340726871fffffa1c173639c40ef6fb7'
METHODS = ('_scored', '_rank', '_question_tags', '_candidates', 'selection_candidates',
           '_selection_score', '_calibrated', '_level')
FUNCTIONS = ('training_turns', 'solve', 'fit', 'score', 'selection', 'shuffled_labels', 'table_of')
MISSING = object()


class Binding:
    def __init__(self, bot, context_type):
        self.bot = bot
        self.before = {name: bot.__dict__.get(name, MISSING) for name in METHODS}
        for name in METHODS:
            descriptor = context_type.__dict__[name]
            method = descriptor.__func__ if isinstance(descriptor, staticmethod) else types.MethodType(descriptor, bot)
            setattr(bot, name, method)

    def restore(self):
        for name, previous in self.before.items():
            if previous is MISSING:
                self.bot.__dict__.pop(name, None)
            else:
                setattr(self.bot, name, previous)


class Components:
    def __init__(self):
        source = {}
        for path, expected in REFERENCE_HASHES.items():
            data = subprocess.check_output(['git', 'show', REFERENCE+':'+path], cwd=ROOT)
            if hashlib.sha256(data).hexdigest() != expected:
                raise RuntimeError('Código PAR2 distinto')
            source[path] = data.decode()
        module = types.ModuleType('leobot._g79_reference')
        module.__package__ = 'leobot'
        exec(compile(source['leobot/context.py'], REFERENCE+':leobot/context.py', 'exec'), module.__dict__)
        self.context_type = module.ContextMixin
        parsed = ast.parse(source['experiments/par2_seleccion.py'])
        selected = ast.Module(body=[node for node in parsed.body if isinstance(node, ast.Assign) or
                                    isinstance(node, ast.FunctionDef) and node.name in FUNCTIONS], type_ignores=[])
        self.learner = {'math': math, 'random': random, 'hashlib': hashlib, 'g60': g60,
                        'CONFIDENCE_BANKS': TRAIN, 'KIOSK': ROOT/'results_v3/kiosco',
                        'businesses': businesses, 'contains': contains, 'plain': plain}
        exec(compile(selected, REFERENCE+':experiments/par2_seleccion.py', 'exec'), self.learner)

    def bind(self, bot):
        return Binding(bot, self.context_type)

    def correct_calibration(self):
        self.learner['g60'] = types.SimpleNamespace(isotonic=isotonic)


def fingerprint():
    files = ('experiments/g79_joint_selection.py', 'experiments/g60_calibrar_confianza.py',
             'experiments/g68_confianza.py', 'experiments/g75_relational_evidence.py',
             'prereg/G-79-complementar-educacion-y-seleccion.md')
    git = lambda *args: subprocess.check_output(['git', *args], cwd=ROOT, text=True).strip()
    if git('rev-parse', 'HEAD:leobot') != ENGINE or git('status', '--porcelain', '--', 'leobot', *files):
        raise RuntimeError('G79 no congelado')
    return {path: hashlib.sha256((ROOT/path).read_bytes()).hexdigest() for path in files}


def replay(path):
    start = time.process_time()
    try:
        components = Components()
        bot = Bot.load(path)
        binding = components.bind(bot)
        result = public_measure(bot)
        binding.restore()
        error = None
    except Exception as exc:
        result, error = None, repr(exc)
    return {'result': result, 'error': error, 'cpu_s': time.process_time()-start,
            'peak_rss_kib': resource.getrusage(resource.RUSAGE_SELF).ru_maxrss}


def main():
    resource.setrlimit(resource.RLIMIT_CPU, (805, 810))
    resource.setrlimit(resource.RLIMIT_AS, (1024**3, 1024**3))
    hashes = fingerprint()
    cpu0, wall0 = time.process_time(), time.monotonic()
    base = ROOT / '.leobot-data/base_kiosco.json'
    if hashlib.sha256(base.read_bytes()).hexdigest() != BASE_SHA:
        raise RuntimeError('Base distinta')
    native_path = ROOT / '.leobot-data/g78_models.json'
    if hashlib.sha256(native_path.read_bytes()).hexdigest() != G78_SHA:
        raise RuntimeError('Educación G78 distinta')
    native = json.loads(native_path.read_text())['localized']
    components = Components()
    ns = components.learner
    bot = Bot.load(base)
    original = json.loads(json.dumps(bot.context_model))
    results, raw, fits, education = {}, {}, [], {}
    evaluation_cpu = 0.

    def measured(name, *, raw_selection=False):
        nonlocal evaluation_cpu
        start = time.process_time()
        result = public_measure(bot, deadline=start+200-evaluation_cpu)
        results[name] = result
        if raw_selection:
            rows = collect(bot, DEV)
            raw[name] = {'core': sum(r['core'] for r in rows),
                         'correct_first': sum(r['core'] and r['y'] for r in rows)}
        evaluation_cpu += time.process_time()-start
        print(json.dumps({'stage': 'measured', 'mode': name, 'result': result, 'raw': raw.get(name)}), flush=True)
        return result

    baseline = measured('baseline')
    assert (baseline['useful_core'], baseline['quotes_without_data']) == (269, 74)
    binding = components.bind(bot)
    reference = measured('reference_disabled')
    assert reference['response_sha256'] == baseline['response_sha256']
    bot.context_model = native
    native_result = measured('native_only')
    assert (native_result['useful_core'], native_result['quotes_without_data']) == (267, 57)
    expected_native = json.loads((ROOT/'results_v3/g78_localized_education.json').read_text())['candidates']['localized']
    assert native_result['response_sha256'] == expected_native['response_sha256']

    original_fit = ns['fit']
    def timed_fit(turns, names):
        if time.process_time()-cpu0-evaluation_cpu > 600:
            raise TimeoutError('G79 agotó educación')
        start = time.process_time()
        fitted = original_fit(turns, names)
        cost = {'cpu_s': time.process_time()-start, 'rows': fitted['rows'],
                'distinct_rows': fitted['distinct_rows'], 'iterations': fitted['iterations']}
        fits.append(cost)
        print(json.dumps({'stage': 'fit', **cost}), flush=True)
        return fitted
    ns['fit'] = timed_fit

    models, selectors, cache = {}, {}, {}
    output_model = ROOT / '.leobot-data/g79_models.json'
    def keep(name, context, learned):
        selectors[name] = ns['table_of'](learned)
        models[name] = {**context, 'selection': selectors[name]}
        output_model.write_text(json.dumps({'models': models, 'education': education,
                                            'reference': REFERENCE, 'sources_sha256': hashes}, ensure_ascii=False))

    bot.context_model = original
    turns = ns['training_turns'](bot)
    names = sorted(next(t['rows'][0][0] for t in turns if t['rows']))
    education['plain'] = {'turns': len(turns), 'candidate_rows': sum(len(t['rows']) for t in turns), 'features': names}
    keep('selector_legacy', original, ns['selection'](turns, names, 6, cache, 'plain'))
    bot.context_model = models['selector_legacy']
    legacy = measured('selector_legacy', raw_selection=True)
    assert (legacy['useful_core'], legacy['quotes_without_data']) == (299, 70), 'PAR2 no reproduce'
    components.correct_calibration()
    keep('selector', original, ns['selection'](turns, names, 6, cache, 'plain'))
    bot.context_model = native
    turns = ns['training_turns'](bot)
    names = sorted(next(t['rows'][0][0] for t in turns if t['rows']))
    education['native'] = {'turns': len(turns), 'candidate_rows': sum(len(t['rows']) for t in turns), 'features': names}
    keep('combined', native, ns['selection'](turns, names, 6, cache, 'native'))
    keep('shuffled', native, ns['selection'](ns['shuffled_labels'](turns), names, 6, cache, 'shuffled'))
    teaching_cpu = time.process_time()-cpu0-evaluation_cpu
    for name in ('selector', 'combined', 'shuffled'):
        bot.context_model = models[name]
        measured(name, raw_selection=True)

    start = time.process_time()
    bot.context_model = models['combined']
    bot.load_context('', '')
    candidate = ROOT / '.leobot-data/g79_candidate.json'
    bot.save(candidate)
    binding.restore()
    del binding, bot, turns, cache
    gc.collect()
    parent_rss = int(next(line.split()[1] for line in Path('/proc/self/status').read_text().splitlines()
                          if line.startswith('VmRSS:')))
    child_run = subprocess.run([sys.executable, '-m', 'experiments.g79_joint_selection', '--replay', str(candidate)],
                               cwd=ROOT, env={**os.environ, 'PYTHONHASHSEED': '1'},
                               capture_output=True, text=True, timeout=45, check=True)
    child = json.loads(child_run.stdout)
    evaluation_cpu += time.process_time()-start+child['cpu_s']
    start = time.process_time()
    bot = Bot.load(base)
    evaluation_cpu += time.process_time()-start
    disabled = measured('disabled')
    controls = {'disabled_exact': disabled['response_sha256'] == baseline['response_sha256'],
                'reference_without_model_exact': reference['response_sha256'] == baseline['response_sha256'],
                'native_without_selector_exact': native_result['response_sha256'] == expected_native['response_sha256'],
                'reload_exact': child['result'] is not None and child['result']['response_sha256'] == results['combined']['response_sha256']}
    rss = max(resource.getrusage(resource.RUSAGE_SELF).ru_maxrss, parent_rss+child['peak_rss_kib'])
    primary = results['combined']
    gates = {'gain': primary['useful_core'] >= baseline['useful_core']+.05*baseline['core'],
             'component_gain': all(primary['useful_core'] >= results[name]['useful_core']+.02*baseline['core']
                                   for name in ('selector', 'selector_legacy', 'native_only')),
             'shuffled_gain': primary['useful_core'] >= results['shuffled']['useful_core']+.02*baseline['core'],
             'absent': primary['quotes_without_data'] <= baseline['quotes_without_data'],
             'controls': all(controls.values()), 'literal': primary['nonliteral_evidence'] == 0,
             'latency': primary['p95_ms'] < 5 and primary['max_ms'] < 5,
             'budget': teaching_cpu <= 600 and evaluation_cpu <= 200 and rss <= 1024**2
                       and time.monotonic()-wall0 <= 1000}
    assert fingerprint() == hashes
    report = {'experiment': 'G79', 'scope': 'spent development; external fixed PAR2 code; no production promotion',
              'repository_engine_sha': ENGINE, 'repository_engine_unchanged': True,
              'effective_selector_reference': REFERENCE, 'reference_sha256': REFERENCE_HASHES,
              'sources_sha256': hashes, 'g78_tables_sha256': G78_SHA, 'base_sha256': BASE_SHA,
              'education': education, 'fits': fits, 'candidates': results, 'selection_without_abstention': raw,
              'controls': controls, 'restart': child, 'gates': gates, 'passes': all(gates.values()),
              'cost': {'teaching_cpu_s': teaching_cpu, 'evaluation_cpu_s': evaluation_cpu,
                       'total_cpu_s': time.process_time()-cpu0+child['cpu_s'], 'wall_s': time.monotonic()-wall0,
                       'peak_rss_kib': rss, 'parent_rss_during_child_kib': parent_rss,
                       'models_bytes': output_model.stat().st_size, 'base_bytes': candidate.stat().st_size}}
    (ROOT / 'results_v3/g79_joint_selection.json').write_text(json.dumps(report, ensure_ascii=False, indent=2)+'\n')
    print(json.dumps({'gates': gates, 'results': results, 'cost': report['cost']}), flush=True)


if __name__ == '__main__':
    if len(sys.argv) == 3 and sys.argv[1] == '--replay':
        print(json.dumps(replay(sys.argv[2])))
    else:
        start_cpu, start_wall = time.process_time(), time.monotonic()
        try:
            main()
        except (TimeoutError, AssertionError) as error:
            (ROOT / 'results_v3/g79_interruption.json').write_text(json.dumps({
                'status': 'interrupted_budget_or_reference', 'error': repr(error),
                'cpu_s': time.process_time()-start_cpu, 'wall_s': time.monotonic()-start_wall,
                'peak_rss_kib': resource.getrusage(resource.RUSAGE_SELF).ru_maxrss,
            }, ensure_ascii=False, indent=2)+'\n')
            raise
